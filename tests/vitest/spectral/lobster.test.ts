// Constructed geometry for translation matching (pymatgen's lists with translations come
// without their structure): bcc Fe, pair 1 = nearest neighbors through translation 0, pair 2 =
// Fe1 and its image one cell along a
const bcc_poscar = `Fe bcc
1.0
  2.83 0.00 0.00
  0.00 2.83 0.00
  0.00 0.00 2.83
Fe
2
Direct
  0.0 0.0 0.0
  0.5 0.5 0.5
`
const bcc_list = ` COHP#  atomMU  atomNU     distance      translation          ICOHP (eV) at eF for spin 1
     1     Fe1     Fe2      2.45085      0     0     0     -0.10218
     2     Fe1     Fe1      2.83000      1     0     0     -0.03100
`

// LOBSTER 2 (no translation): matched by sites and length
const old_list = ` COHP#  atomMU  atomNU  distance  ICOHP(eF)  for spin  1
     1     Fe1     Fe2      2.45085     -0.4   8
`
// labels of the pairs `list` matches to `bonds` in `structure`, undefined where none does
const matched_labels = (
  list: IcohpList,
  unit_cell: AnyStructure,
  bonds: BondPair[],
  structure: AnyStructure,
) => icohp_bond_colors(list, unit_cell, (_strength, { label }) => label)(bonds, structure)

describe(`icohp_bond_colors`, () => {
  const bcc_cell = parse_poscar(bcc_poscar)
  const rendered: AnyStructure = get_pbc_image_sites(bcc_cell, { completion: `none` })
  const list = parse_icohplist(bcc_list, `COHP`)
  // the bond from site_idx_1 to site_idx_2 (rendered indices) at their own positions, the second
  // shifted by cell_shift lattice vectors
  const bond = (site_idx_1: number, site_idx_2: number, cell_shift: Vec3 = [0, 0, 0]) => {
    const [site_1, site_2] = [get_site(rendered, site_idx_1), get_site(rendered, site_idx_2)]
    if (!site_1 || !site_2) throw new Error(`no site ${site_idx_1} or ${site_idx_2}`)
    const pos_2 = site_2.xyz.map((val, axis) => val + 2.83 * cell_shift[axis]) as Vec3
    const bond_length = Math.hypot(...pos_2.map((val, axis) => val - site_1.xyz[axis]))
    return { pos_1: site_1.xyz, pos_2, site_idx_1, site_idx_2, bond_length }
  }
  // Fe1's image one cell along a, as a rendered site
  const image_idx = rendered.sites.findIndex(
    ({ provenance, abc }) => provenance?.image_of === 0 && abc.join(`,`) === `1,0,0`,
  )

  // pair 1: Fe1 -> Fe2 through translation 0, i.e. vector (1.415, 1.415, 1.415); an equal-length
  // Fe1-Fe2 bond along another direction is a different LOBSTER pair. Pair 2: Fe1 to its image
  // along a, either way round and via an image site, not along b.
  // oxfmt-ignore
  test.each([
    [`translation vector`, bcc_list, [
      [bond(0, 1), `1`], [bond(1, 0), `1`], [bond(0, 1, [-1, 0, 0]), undefined],
      [bond(0, 0, [1, 0, 0]), `2`], [bond(0, 0, [-1, 0, 0]), `2`], [bond(0, image_idx), `2`],
      [bond(0, 0, [0, 1, 0]), undefined],
    ]],
    [`LOBSTER 2 sites and length`, old_list, [
      [bond(0, 1, [-1, 0, 0]), `1`], [bond(1, 0), `1`], [bond(0, 0, [1, 0, 0]), undefined],
    ]],
  ] as const)(`matches bonds by %s`, (_name, text, cases) => {
    expect(image_idx).toBeGreaterThan(1)
    const bonds = cases.map(([bond_pair]) => bond_pair)
    expect(matched_labels(parse_icohplist(text, `COHP`), bcc_cell, bonds, rendered)).toEqual(
      cases.map(([, label]) => label),
    )
  })

  test(`colors follow bonding strength (-ICOHP), undefined for unmatched bonds`, () => {
    const seen: [number, string][] = []
    let faded = false
    const colors = icohp_bond_colors(list, bcc_cell, (strength, entry) => {
      seen.push([strength, entry.label])
      return faded ? `gray` : `hsl(${Math.round(strength * 1000)}, 50%, 50%)`
    })
    const bonds = [bond(0, 1), bond(0, 0, [1, 0, 0]), bond(0, 0, [0, 0, 1])]
    expect(colors(bonds, rendered)).toEqual([
      `hsl(102, 50%, 50%)`,
      `hsl(31, 50%, 50%)`,
      undefined,
    ])
    expect(seen.map(([strength, label]) => [Number(strength.toFixed(5)), label])).toEqual([
      [0.10218, `1`],
      [0.031, `2`],
    ])
    // recoloring the same bonds (e.g. on hover) calls color_fn once per pair, not per bond
    faded = true
    expect(colors(bonds, rendered)).toEqual([`gray`, `gray`, undefined])
    expect(seen).toHaveLength(4)
  })

  test(`rejects pairs the structure can't hold: missing site or other distance`, () => {
    const list_3 = parse_icohplist(bcc_list.replaceAll(`Fe2`, `Fe3`), `COHP`)
    expect(() => icohp_bond_colors(list_3, bcc_cell, String)).toThrow(
      /Fe3 is not in the structure/,
    )
    const stretched = parse_poscar(bcc_poscar.replaceAll(`2.83`, `2.90`))
    expect(() => pair_vector(list.entries[0], stretched)).toThrow(
      /pair 1 is 2.45085 Å long, 2.51147 Å in the structure/,
    )
  })
})

// Bundled demo samples (src/site/electronic/lobster/<sample>/): every folder parses (the
// registry throws otherwise), names its source and holds files that agree with each other
describe.each(Object.values(lobster_samples))(`sample $name`, (sample) => {
  // the shown note links the pinned upstream commit; the upstream MIT notice travels with the
  // copied files in LICENSE.txt, which the registry keeps out of the sample (not ignored)
  test(`has a source, its license and COHP and COOP or COBI files`, () => {
    expect(sample.source).toMatch(
      /^Real LOBSTER output .*\[pymatgen test files\]\(https:\/\/github\.com\/materialsproject\/pymatgen-test-files\/tree\/[0-9a-f]{40}\//,
    )
    const license = readFileSync(
      `src/site/electronic/lobster/${sample.name}/LICENSE.txt`,
      `utf8`,
    )
    expect(license).toMatch(/MIT License[\s\S]*Copyright \(c\)/)
    expect([...sample.by_kind.keys()]).toEqual(
      sample.name.endsWith(`COBI`) ? [`COBI`] : [`COHP`, `COOP`],
    )
    expect(sample.ignored).toEqual([])
  })

  test.each([...sample.by_kind])(`%s: curves, list and structure agree`, (_kind, parsed) => {
    const { cohp, icohp } = parsed
    const { structure } = sample
    if (!icohp || !structure || !(`lattice` in structure))
      throw new Error(`sample ${sample.name} lacks a list or a periodic POSCAR`)
    const n_energies = cohp.energies.length
    for (const { values, integrated } of [cohp.average, ...cohp.bonds]) {
      for (const { up, down } of [values, integrated]) {
        expect(up).toHaveLength(n_energies)
        expect(down?.length).toBe(cohp.spin_polarized ? n_energies : undefined)
      }
    }
    // LOBSTER's list holds the CAR's running integral at E_F, digit for digit
    const fermi_idx = cohp.energies.indexOf(0)
    expect(fermi_idx).toBeGreaterThan(0)
    expect(icohp.entries.map(({ label, value }) => [label, value])).toEqual(
      cohp.bonds.map(({ label, integrated: { up, down } }) => [
        label,
        { up: up[fermi_idx], ...(down && { down: down[fermi_idx] }) },
      ]),
    )
    // orbital pairs too; the trimmed LaTaN2O COBICAR drops those that are 0 at every energy
    for (const [idx, entry] of icohp.entries.entries()) {
      const bond = cohp.bonds[idx]
      const at_fermi = new Map(
        bond.orbitals.map(({ key, integrated }) => [key, integrated.up[fermi_idx]]),
      )
      for (const { orbitals, value } of entry.orbitals)
        expect([orbitals, value.up]).toEqual([
          orbitals,
          at_fermi.get(orbital_key(bond.label, orbitals)) ?? 0,
        ])
      expect(entry.orbitals.length).toBeGreaterThanOrEqual(bond.orbitals.length)
    }
    // every pair's atoms sit at the listed distance (within 5e-4 Å: BiSe's POSCAR is off LOBSTER's
    // by up to 8.4e-5 Å, pymatgen agrees) through its translation, or some translation in LOBSTER
    // 2 lists; the matcher finds each pair on that bond
    const to_cart = create_frac_to_cart(structure.lattice.matrix)
    const steps = [-1, 0, 1]
    const shifts = steps.flatMap((step_a) =>
      steps.flatMap((step_b) => steps.map((step_c): Vec3 => [step_a, step_b, step_c])),
    )
    const bonds = icohp.entries.map(({ label, atoms, length, translation }) => {
      const [xyz_1, xyz_2] = atoms.map(({ site_idx }) => structure.sites[site_idx].xyz)
      const dist = (pos: Vec3) => Math.hypot(...pos.map((val, axis) => val - xyz_1[axis]))
      const pos_2 = (translation ? [translation] : shifts)
        .map((shift) => add(xyz_2, to_cart(shift)))
        .find((pos) => Math.abs(dist(pos) - length) < 5e-4)
      if (!pos_2)
        throw new Error(`pair ${label}: no image of ${atoms[1].label} at ${length} Å`)
      const [site_idx_1, site_idx_2] = atoms.map((atom) => atom.site_idx)
      return { pos_1: xyz_1, pos_2, site_idx_1, site_idx_2, bond_length: dist(pos_2) }
    })
    expect(matched_labels(icohp, structure, bonds, structure)).toEqual(
      icohp.entries.map(({ label }) => label),
    )
  })
})
