export type SceneExportFormat = `stl` | `obj` | `glb`

// Whether a material has a Color-like base color, duck-typed since a bundle without our
// `three` alias carries two three copies and Threlte-made materials fail instanceof checks.
function has_color_property(mat: Material): mat is Material & { color: Color } {
  const { color } = mat as { color?: { r?: unknown; g?: unknown; b?: unknown } | null }
  return [color?.r, color?.g, color?.b].every((channel) => typeof channel === `number`)
}

// Gradient bond meshes keep their two per-instance colors in these geometry attributes (read
// by a TSL node graph), so their color is recovered from there, not the material
const has_bond_gradient_attributes = (geometry: BufferGeometry): boolean =>
  Boolean(
    geometry.getAttribute(`instanceColorStart`) && geometry.getAttribute(`instanceColorEnd`),
  )

// Remove per-instance and non-standard color attributes that cause export issues.
function clean_geometry_for_export(geometry: BufferGeometry): void {
  for (const attr_name of Object.keys(geometry.attributes)) {
    const lower_name = attr_name.toLowerCase()
    if (
      geometry.attributes[attr_name] instanceof InstancedBufferAttribute ||
      lower_name.includes(`instance`) ||
      (lower_name.includes(`color`) && lower_name !== `color`)
    )
      geometry.deleteAttribute(attr_name)
  }
}

// Generate MTL (Wavefront Material) content from scene materials.
export function generate_mtl_content(scene: Object3D): string {
  const lines: string[] = [`# MTL file generated by MatterViz`, ``]
  const processed_materials = new Set<string>()
  // MTLLoader reads Kd/Ka as sRGB, so linear channels round-trip ~2x too dark: convert through
  // our own Color (has_color_property duck-types a possibly foreign three copy).
  const srgb_color = new Color()
  const fmt = (val: number) => clamp01(val).toFixed(6)
  // `scale` is applied in linear light before encoding — 20% ambient reflectance means 20% of
  // the linear diffuse, and scaling the encoded value instead would yield about 4%.
  const encode_srgb = (color: { r: number; g: number; b: number }, scale: number): string => {
    srgb_color.setRGB(color.r * scale, color.g * scale, color.b * scale)
    const { r: red, g: green, b: blue } = srgb_color.getRGB(srgb_color, SRGBColorSpace)
    return `${fmt(red)} ${fmt(green)} ${fmt(blue)}`
  }

  scene.traverse((object) => {
    if (!(object instanceof Mesh)) return

    const materials = Array.isArray(object.material) ? object.material : [object.material]
    for (const mat of materials) {
      // oxlint-disable-next-line @typescript-eslint/prefer-nullish-coalescing -- empty name should use default
      const mat_name = mat.name || `default_material`
      if (processed_materials.has(mat_name)) continue
      processed_materials.add(mat_name)

      const color = has_color_property(mat) ? mat.color : { r: 1, g: 1, b: 1 }
      const opacity = `opacity` in mat && typeof mat.opacity === `number` ? mat.opacity : 1.0
      lines.push(
        `newmtl ${mat_name}`,
        `Kd ${encode_srgb(color, 1)}`,
        `Ka ${encode_srgb(color, 0.2)}`, // Ambient is typically a fraction of diffuse
        `Ks 0.500000 0.500000 0.500000`,
        `Ns 96.078431`, // Specular exponent
        `d ${opacity.toFixed(6)}`, // Transparency (d = 1.0 is fully opaque)
        `illum 2`, // Illumination model (2 = highlight on)
        ``,
      )
    }
  })

  return lines.join(`\n`)
}

// Three's InstancedMesh (flag duck-typed for the same two-copies reason as above) or one of
// the structure viewer's instanced-geometry meshes
type ExportInstances = InstancedMesh | AtomInstances | ArrowMesh | BondMesh
const is_instanced_mesh = (obj: Object3D): obj is ExportInstances =>
  obj instanceof AtomInstances ||
  obj instanceof ArrowMesh ||
  obj instanceof BondMesh ||
  (obj as { isInstancedMesh?: boolean }).isInstancedMesh === true

// Copy of `scene` with every InstancedMesh expanded into a Group of plain Meshes (one per
// instance, carrying its resolved color), since the GLB/OBJ exporters don't handle instancing
export function convert_instanced_meshes_to_regular<T extends Object3D>(scene: T): T {
  const cloned_scene = scene.clone()
  const cloned_meshes: ExportInstances[] = []
  // Depth-only meshes (translucent surfaces' depth pre-passes, see depth_prepass_props) draw
  // nothing, so exporting them would duplicate their visible twin's geometry
  const depth_only: Mesh[] = []
  cloned_scene.traverse((object) => {
    if (is_instanced_mesh(object)) cloned_meshes.push(object)
    else if (
      object instanceof Mesh &&
      [object.material].flat().every((mat) => !mat.colorWrite)
    )
      depth_only.push(object)
  })
  for (const mesh of depth_only) mesh.removeFromParent()

  for (const [mesh_idx, instanced_mesh] of cloned_meshes.entries()) {
    const parent = instanced_mesh.parent
    if (!parent) continue

    const group = new Group()
    group.name = instanced_mesh.name

    const { geometry } = instanced_mesh
    const bond_ends = has_bond_gradient_attributes(geometry)
      ? [
          geometry.getAttribute(`instanceColorStart`),
          geometry.getAttribute(`instanceColorEnd`),
        ]
      : null
    const instance_color_attr =
      instanced_mesh instanceof AtomInstances || instanced_mesh instanceof ArrowMesh
        ? instanced_mesh.colors
        : instanced_mesh.instanceColor
    const source_material = Array.isArray(instanced_mesh.material)
      ? instanced_mesh.material[0]
      : instanced_mesh.material
    const material_color = has_color_property(source_material) ? source_material.color : null
    const material_tint = material_color ?? new Color(1, 1, 1)

    // One geometry clone shared by every instance mesh (exporters dedupe shared buffers), with
    // the per-instance color attributes stripped: they break GLTF accessor-count validation.
    const shared_geometry = new BufferGeometry().copy(instanced_mesh.geometry)
    clean_geometry_for_export(shared_geometry)

    // Share exact resolved colors: one material per atom would dwarf the geometry.
    const materials = new Map<string, MeshStandardMaterial>()
    const get_material = (color: Color | null): MeshStandardMaterial => {
      const key = color
        ? color
            .toArray()
            .map((value) => (Object.is(value, -0) ? `-0` : value))
            .join(`,`)
        : ``
      const cached = materials.get(key)
      if (cached) return cached
      // Keep the face culling: double-sided partial-occupancy caps vanish from behind otherwise
      const { side } = source_material
      const material = new MeshStandardMaterial({ metalness: 0.1, roughness: 0.5, side })
      material.name = `material_${mesh_idx}_${materials.size}`
      if (color) material.color.copy(color)
      materials.set(key, material)
      return material
    }

    const instance_color = new Color()
    const instance_matrix = new Matrix4()
    const combined_matrix = new Matrix4()
    for (let idx = 0; idx < instanced_mesh.count; idx++) {
      instanced_mesh.getMatrixAt(idx, instance_matrix)

      // a gradient bond takes the midpoint of its start and end colors
      const resolved_color = bond_ends
        ? idx < bond_ends[0].count
          ? new Color()
              .fromBufferAttribute(bond_ends[0], idx)
              .add(instance_color.fromBufferAttribute(bond_ends[1], idx))
              .multiplyScalar(0.5)
          : null
        : instance_color_attr
          ? instance_color
              .fromBufferAttribute(instance_color_attr, idx)
              .multiply(material_tint)
          : material_color
      const material = get_material(resolved_color)
      const mesh = new Mesh(shared_geometry, material)
      combined_matrix.multiplyMatrices(instanced_mesh.matrix, instance_matrix)
      // Keep the captured matrix directly: decomposing a collapsed (zero-radius) instance
      // creates NaN rotations, and recomposition needlessly perturbs ordinary transforms.
      mesh.matrix.copy(combined_matrix)
      mesh.matrixAutoUpdate = false

      group.add(mesh)
    }

    parent.remove(instanced_mesh)
    parent.add(group)
  }

  cloned_scene.updateMatrixWorld(true)

  // Strip leftover per-instance color attributes from any mesh the instancing pass didn't
  // rewrite, so they can't trip GLTF accessor-count validation.
  cloned_scene.traverse((object) => {
    if (object instanceof Mesh && has_bond_gradient_attributes(object.geometry)) {
      object.geometry = object.geometry.clone()
      clean_geometry_for_export(object.geometry)
    }
  })

  return cloned_scene
}

const MODEL_HINTS: Record<SceneExportFormat, string> = {
  stl: `3D printing`,
  obj: `Wavefront`,
  glb: `web/AR`,
}
// Export pane items saving the model get_model returns (nothing while it has none) per format
export const model_export_items = (
  get_model: () => Object3D | null | undefined,
  formats: SceneExportFormat[],
) =>
  formats.map((format) => ({
    label: format.toUpperCase(),
    hint: MODEL_HINTS[format],
    on_download: ({ filename, save }: { filename: string; save: FileSaver }) => {
      const model = get_model()
      return model && export_scene_as(model, format, filename, save)
    },
  }))

// Download `scene` as `<basename>.<format>` (OBJ plus a companion `.mtl` of material colors,
// GLB as binary glTF), instanced meshes expanded first. Rejects on exporter errors.
export async function export_scene_as(
  scene: Object3D,
  format: SceneExportFormat,
  basename: string,
  save: FileSaver = download,
): Promise<void> {
  const export_root = convert_instanced_meshes_to_regular(scene)
  if (format === `stl`) {
    const { STLExporter } = await import(`three/examples/jsm/exporters/STLExporter.js`)
    const result = new STLExporter().parse(export_root, { binary: true })
    // Binary STL returns DataView, convert to ArrayBuffer for Blob
    const buffer = result instanceof DataView ? result.buffer : result
    await save(buffer, `${basename}.stl`, `application/octet-stream`)
  } else if (format === `obj`) {
    const { OBJExporter } = await import(`three/examples/jsm/exporters/OBJExporter.js`)
    // OBJExporter writes `usemtl` for named materials only, so every Threlte-made (unnamed)
    // one exported without its color: the clone gets a named copy per distinct material
    const named_copies = new Map<Material, Material>()
    export_root.traverse((object) => {
      if (!(object instanceof Mesh) || Array.isArray(object.material) || object.material.name)
        return
      const copy =
        named_copies.get(object.material) ??
        Object.assign(object.material.clone(), { name: `material_${named_copies.size}` })
      named_copies.set(object.material, copy)
      object.material = copy
    })
    const mtl_filename = `${basename}.mtl`
    // Material library reference goes at the top of the OBJ file
    const obj_content = `mtllib ${mtl_filename}\n${new OBJExporter().parse(export_root)}`
    await save(obj_content, `${basename}.obj`, `text/plain`)
    // Small delay to prevent some browsers from blocking rapid successive downloads as
    // potential abuse. A more robust solution might be to zip both files together.
    const mtl_content = generate_mtl_content(export_root)
    await new Promise((resolve) => setTimeout(resolve, 100))
    await save(mtl_content, mtl_filename, `text/plain`)
  } else if (format === `glb`) {
    const { GLTFExporter } = await import(`three/examples/jsm/exporters/GLTFExporter.js`)
    const buffer = await new GLTFExporter()
      .parseAsync(export_root, { binary: true })
      .catch((error: unknown) => {
        throw to_error(error)
      })
    if (!(buffer instanceof ArrayBuffer))
      throw new TypeError(`GLB export returned ${typeof buffer} instead of ArrayBuffer`)
    await save(buffer, `${basename}.glb`, `model/gltf-binary`)
  } else throw new Error(`Unsupported scene export format: ${format}`)
}
