import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { gunzipSync } from 'node:zlib'

const gz_path = resolve(import.meta.dirname, `../lib/element/data.json.gz`)
const out_dir = resolve(import.meta.dirname, `../../dist/element`)

mkdirSync(out_dir, { recursive: true })
const json = JSON.parse(gunzipSync(readFileSync(gz_path)).toString(`utf8`))
// Keep runtime re-exports below synchronized with src/lib/element/data.ts.
writeFileSync(
  resolve(out_dir, `data.js`),
  `// Generated by src/scripts/package-dist-assets.mjs
const element_data = ${JSON.stringify(json)};
export const element_by_symbol = new Map(
  element_data.map((element) => [element.symbol, element]),
);
export default element_data;
`,
)
